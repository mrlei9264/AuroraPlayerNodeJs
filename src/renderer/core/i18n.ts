const dicts: Record<Lang, typeof en> = { en, zh }

export type TKey = keyof typeof en

export function playbackErrorKey(message: string | null | undefined): TKey {
  const normalized = String(message ?? '').toLowerCase()
  if (normalized.includes('loading timed out') || normalized.includes('load timeout')) return 'playbackLoadTimeout'
  if (normalized.includes('network error') || normalized.includes('connection') || normalized.includes('http error')) return 'playbackNetworkError'
  if (normalized.includes('decode') || normalized.includes('decoder')) return 'playbackDecodeError'
  if (normalized.includes('not supported') || normalized.includes('unsupported') || normalized.includes('format')) return 'playbackUnsupportedError'
  return 'loadError'
}

export function makeT(lang: Lang): (key: TKey | string, vars?: Record<string, string | number>) => string {
  const d = dicts[lang] ?? en
  return (key, vars) => {
    const resolve = (dict: Record<string, unknown>): unknown => {
      if (key in dict) return dict[key]
      if (key.includes('.')) {
        let cur: unknown = dict
        for (const part of key.split('.')) {
          if (cur == null || typeof cur !== 'object') return undefined
          cur = (cur as Record<string, unknown>)[part]
        }
        return cur
      }
      return undefined
    }
    const v = resolve(d) ?? resolve(en) ?? key
    if (typeof v === 'string' && vars) {
      let out = v
      for (const [k, val] of Object.entries(vars)) out = out.replace(`{${k}}`, String(val))
      return out
    }
    return typeof v === 'string' ? v : key
  }
}
